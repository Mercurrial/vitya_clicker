/// Понятные меры для нагнанного: «если слить всё в одно место».
///
/// «8.4М л» ничего не говорит — число больше, чем помещается в голове. А
/// «три олимпийских бассейна» говорит сразу, и в этом весь смысл строки. Меры
/// бытовые и узнаваемые, от рюмки до Байкала: над масштабом смеёмся, над
/// Витей — нет.
///
/// Считается при показе и в сейв не идёт: это пересказ факта (сколько
/// нагнано), а не факт.
library;

/// Во что переливаем.
class Measure {
  /// Формы для 1, 2 и 5: «ванна», «ванны», «ванн».
  final String one;
  final String few;
  final String many;

  /// Сколько литров помещается.
  final double litres;

  const Measure(this.one, this.few, this.many, this.litres);

  /// Сколько таких наберётся из [ml] миллилитров.
  double countIn(double ml) => ml / (litres * 1000);
}

/// Рюмка — чтобы и у новичка было что показать.
const Measure kShot = Measure('рюмка', 'рюмки', 'рюмок', 0.05);

/// Трёхлитровая банка — та самая, с которой Витя начинал. Её строка есть
/// всегда, как только набралась первая.
const Measure kJar = Measure(
    'трёхлитровая банка', 'трёхлитровые банки', 'трёхлитровых банок', 3);

/// Меры по возрастанию. Объёмы — справочные, с округлением: точность тут не
/// нужна, нужен масштаб.
const List<Measure> kMeasures = [
  kShot,
  kJar,
  Measure('ведро', 'ведра', 'вёдер', 10),
  Measure('ванна', 'ванны', 'ванн', 200),
  Measure('железнодорожная цистерна', 'железнодорожные цистерны',
      'железнодорожных цистерн', 60e3),
  Measure('олимпийский бассейн', 'олимпийских бассейна',
      'олимпийских бассейнов', 2.5e6),
  // 908 км³.
  Measure('Ладожское озеро', 'Ладожских озера', 'Ладожских озёр', 9.08e14),
  // 23 615 км³.
  Measure('Байкал', 'Байкала', 'Байкалов', 2.3615e16),
];

/// Во что перелить [ml]: банки и самая крупная мера, которой набралась хотя
/// бы одна.
///
/// Банки — всегда первыми: с одной банки игра начинается, и это число растёт
/// у игрока на глазах. Крупная мера — вторым, если она крупнее банки. Пока
/// не набралось и банки — рюмки. Пусто — не набралось и рюмки.
List<(double, Measure)> pourInto(double ml) {
  if (ml <= 0 || !ml.isFinite) return const [];
  if (kJar.countIn(ml) < 1) {
    final shots = kShot.countIn(ml);
    return shots < 1 ? const [] : [(shots, kShot)];
  }

  final out = [(kJar.countIn(ml), kJar)];
  final biggest = kMeasures.lastWhere((m) => m.countIn(ml) >= 1);
  if (biggest.litres > kJar.litres) out.add((biggest.countIn(ml), biggest));
  return out;
}
