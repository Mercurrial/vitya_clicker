/// Идущее прямо сейчас событие.
class ActiveEvent {
  final GarageEvent event;

  /// Сколько осталось.
  final Duration remaining;

  const ActiveEvent({required this.event, required this.remaining});
}

/// Длина окна, в которое можно сдать.
///
/// Пятнадцать минут — чтобы успел и тот, кто держит игру открытой, и тот, кто
/// заглянул между делом. Короче окно превращает событие в наказание за то, что
/// человек живёт своей жизнью.
const Duration kEventWindow = Duration(minutes: 15);

/// Шаг расписания. Внутри каждого отрезка событие либо есть, либо нет.
const Duration _slot = Duration(minutes: 40);

/// В какой доле отрезков событие случается.
const int _chancePercent = 55;

/// Что происходит в гараже в момент [now].
///
/// Чистая функция времени: одинакова на всех устройствах, ничего не хранит и
/// не требует, чтобы игра была запущена.
ActiveEvent? eventAt(DateTime now) {
  final ms = now.toUtc().millisecondsSinceEpoch;
  final slotMs = _slot.inMilliseconds;
  final windowMs = kEventWindow.inMilliseconds;

  final slot = ms ~/ slotMs;
  final h = scheduleHash(slot);

  if (h % 100 >= _chancePercent) return null;

  // Начало окна гуляет внутри отрезка — иначе события приходили бы ровно в
  // ноль минут каждого часа, и «случайность» была бы видна невооружённым глазом.
  final start = (h >> 7) % (slotMs - windowMs);
  final offset = ms - slot * slotMs;
  if (offset < start || offset >= start + windowMs) return null;

  return ActiveEvent(
    event: kGarageEvents[(h >> 3) % kGarageEvents.length],
    remaining: Duration(milliseconds: start + windowMs - offset),
  );
}

/// Перемешивание битов. Нужен не криптографический хеш, а просто число, у
/// которого соседние аргументы дают непохожие результаты: иначе события
/// выстроятся в лесенку.
///
/// Когда-то общий для событий, ШУХЕРА и неприятностей; те вырезаны в балансе
/// v7, и теперь им пользуются только события.
///
/// ## Почему множители маленькие
///
/// В браузере `int` — это double: точных в нём 53 бита, а не 64. Прошлая
/// версия умножала тридцатибитное число на тридцатибитное, произведение
/// уходило за 2^53 и молча теряло младшие биты — ровно те, что остаются после
/// маски. Веб-версия считала своё расписание, телефон своё, и гость у друзей
/// приходил в разное время, хотя весь смысл расписания из часов — одно на всех.
///
/// Теперь каждое умножение — тридцать бит на шестнадцать, меньше 2^46, и
/// результат одинаков на любой платформе. Это закреплено тестом.
int scheduleHash(int x) {
  var h = x & 0x3FFFFFFF;
  h = (h * 0x9E37 + 0x7F4A) & 0x3FFFFFFF;
  h ^= h >> 15;
  h = (h * 0x85EB) & 0x3FFFFFFF;
  h ^= h >> 13;
  h = (h * 0xC2B3) & 0x3FFFFFFF;
  h ^= h >> 16;
  return h;
}

/// Наибольший множитель в [scheduleHash] — для теста на переносимость.
const int kScheduleHashMaxFactor = 0xC2B3;
