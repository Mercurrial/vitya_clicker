/// Случайные события: кому-то срочно понадобился самогон.
///
/// ## Зачем
///
/// Постоянный покупатель один — Петрович, берёт всё и всегда по рынку. Это
/// правильно: трое постоянных покупателей выглядели выбором, но выбора не
/// давали. Только вместе с ними ушёл и повод заглянуть в игру просто так.
///
/// Событие возвращает этот повод, ничего не усложняя. Раз в пару часов на
/// пятнадцать минут появляется второй покупатель, который платит втрое, но
/// берёт только хороший сорт. Решение при этом остаётся тем же самым, каким
/// оно было всегда — «сдать сейчас или довести СОРТ», — просто теперь у него
/// появляется срок.
///
/// ## Почему расписание выводится из часов, а не разыгрывается
///
/// Соблазн был написать `Random()` и складывать «следующее событие в» в сейв.
/// Так делать нельзя, и причина та же, по которой такова цена на рынке:
///
/// * **Оффлайн.** Игра начисляет доход за время отсутствия, прогоняя тот же
///   движок. Если бы события хранились в состоянии, их пришлось бы отдельно
///   «доигрывать» при возвращении — или молча терять.
/// * **Сейв.** Всё, что кладётся в сохранение, надо версионировать и мигрировать
///   до конца времён. Расписание, которое считается из часов, не кладётся никуда.
/// * **Проверяемость.** Чистая функция времени проверяется тестом за секунду:
///   подставил дату — получил ответ. Генератор со скрытым состоянием так не
///   проверяется.
///
/// Плата за это — события у всех игроков случаются одновременно. Для игры,
/// в которую играют несколько друзей, это скорее плюс: есть что обсудить.
library;

import 'buyers.dart';

/// Кто и зачем пришёл.
class GarageEvent {
  final String id;

  /// Заголовок плашки: «Свадьба у Зинки».
  final String title;

  /// Строка под суммой — зачем им столько.
  final String note;

  /// Чего не хватает, чтобы сдать. Показывается, пока сделка недоступна.
  final String lockedNote;

  /// Множитель к цене.
  final double multiplier;

  /// С какого сорта берут.
  final int minSortIndex;

  const GarageEvent({
    required this.id,
    required this.title,
    required this.note,
    required this.lockedNote,
    required this.multiplier,
    required this.minSortIndex,
  });

  /// Событие как покупатель — чтобы движок не знал про события вовсе.
  ///
  /// Продажа устроена одинаково для всех: [Buyer] уже описывает и множитель, и
  /// требования к сорту, и то, что хороший покупатель забирает сорт с собой.
  /// Событию достаточно превратиться в покупателя, и ни `sellTo`, ни сейв,
  /// ни автопродажа про события так и не узнают.
  Buyer get asBuyer => Buyer(
        id: 'event:$id',
        name: title,
        multiplier: multiplier,
        minSortIndex: minSortIndex,
        minMl: 0,
        maxMl: null,
        // Событие платит втрое именно за хороший товар — и уносит его вместе
        // с сортом. Иначе выгоднее было бы копить сорт вечно и сдавать только
        // по событиям, а Петрович стал бы кнопкой «потерять деньги».
        consumesSort: true,
        note: note,
        lockedNote: lockedNote,
      );
}

