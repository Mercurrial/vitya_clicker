/// Пиксельные значки целей — у каждой цели свой.
///
/// Прошлый набор раздавал девять значков на двадцать целей: «Первая капля»
/// и «Рука набита» были одним пальцем, «Целый литр», «Первая тысяча» и
/// «Миллион» — одной каплей. Сетка целей превращалась в угадайку, и отличить
/// цель от цели можно было только по подписи.
///
/// Значки собираются в `tools/goal_icons_lab.py` теми же примитивами и той
/// же палитрой, что и аппараты, — и лежат в `goal_icons_gen.dart`.
library;

import 'pixel_sprite.dart';

part 'goal_icons_gen.dart';

/// Значок цели. Незнакомый идентификатор получает костёр первой цели, а не
/// пустое место: новая цель без значка — недосмотр, но не дыра в сетке.
PixelSprite goalIcon(String id) => _kGoalIcons[id] ?? _kGoalIcons['a_first_tap']!;

/// Есть ли у цели свой значок — для теста.
bool hasGoalIcon(String id) => _kGoalIcons.containsKey(id);
